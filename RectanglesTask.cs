using System;

namespace Rectangles;

/// <summary>
/// Статический класс с методами для работы с двумя прямоугольниками,
/// стороны которых параллельны осям координат.
/// </summary>
/// <remarks>
/// <para>
/// Координаты целочисленные. Используется «графическая» система координат:
/// верхний левый угол экрана — это (0, 0), а ось Y направлена вниз.
/// Поэтому у прямоугольника нижняя граница (<see cref="Rectangle.Bottom"/>)
/// имеет координату больше, чем верхняя (<see cref="Rectangle.Top"/>).
/// </para>
/// <para>
/// Граница и внутренность прямоугольника считаются частью прямоугольника,
/// то есть прямоугольник — это замкнутая область (включая вырожденные случаи:
/// отрезки при нулевой ширине или высоте и точки при обоих нулевых размерах).
/// </para>
/// <para>
/// Решение основано на разложении двумерной задачи на две одномерные:
/// проекции прямоугольников на оси X и Y — это замкнутые отрезки
/// [Left, Right] и [Top, Bottom]. Два прямоугольника имеют общую точку
/// тогда и только тогда, когда их проекции имеют общую точку по обеим осям.
/// </para>
/// </remarks>
public static class RectanglesTask
{
    /// <summary>
    /// Определяет, есть ли у двух прямоугольников хотя бы одна общая точка.
    /// Касание границами (по стороне или углу) также считается пересечением.
    /// </summary>
    /// <param name="r1">Первый прямоугольник.</param>
    /// <param name="r2">Второй прямоугольник.</param>
    /// <returns>
    /// <see langword="true"/>, если прямоугольники имеют хотя бы одну общую точку
    /// (пересекаются, касаются или один лежит внутри другого); иначе <see langword="false"/>.
    /// </returns>
    /// <remarks>
    /// Условие пересечения проверяется отдельно по каждой оси: между замкнутыми
    /// отрезками [aStart, aEnd] и [bStart, bEnd] есть общая точка тогда и только
    /// тогда, когда <c>Max(aStart, bStart) &lt;= Min(aEnd, bEnd)</c>.
    /// Это работает и для вырожденных прямоугольников (отрезков и точек).
    /// </remarks>
    public static bool AreIntersected(Rectangle r1, Rectangle r2)
    {
        // Результат проверки пересечения прямоугольников по оси X:
        // true — если замкнутые отрезки-проекции [r1.Left, r1.Right] и
        // [r2.Left, r2.Right] имеют хотя бы одну общую точку; иначе false.
        var intersectedByX = HasCommonPoint(r1.Left, r1.Right, r2.Left, r2.Right);

        // Результат проверки пересечения прямоугольников по оси Y:
        // true — если замкнутые отрезки-проекции [r1.Top, r1.Bottom] и
        // [r2.Top, r2.Bottom] имеют хотя бы одну общую точку; иначе false.
        // Учтите: ось Y направлена вниз, поэтому Top < Bottom.
        var intersectedByY = HasCommonPoint(r1.Top, r1.Bottom, r2.Top, r2.Bottom);

        // Прямоугольники имеют общую точку тогда и только тогда, когда
        // общие точки есть у проекций и на ось X, и на ось Y одновременно.
        return intersectedByX && intersectedByY;
    }

    /// <summary>
    /// Вычисляет площадь пересечения двух прямоугольников.
    /// </summary>
    /// <param name="r1">Первый прямоугольник.</param>
    /// <param name="r2">Второй прямоугольник.</param>
    /// <returns>
    /// Площадь общей части прямоугольников как целое число. Если прямоугольники
    /// не пересекаются, пересекаются только границами либо один из них вырожден
    /// (нулевая ширина или высота), результат равен 0.
    /// </returns>
    /// <remarks>
    /// Пересечение двух прямоугольников со сторонами, параллельными осям, —
    /// это прямоугольник (возможно, вырожденный), чьи стороны равны длинам
    /// перекрытия проекций исходных прямоугольников на соответствующие оси.
    /// </remarks>
    public static int IntersectionSquare(Rectangle r1, Rectangle r2)
    {
        // Ширина пересечения — длина перекрытия проекций прямоугольников на ось X,
        // то есть длина общего участка отрезков [r1.Left, r1.Right] и [r2.Left, r2.Right].
        // Равна 0, если по оси X перекрытия нет или оно состоит из одной точки (касание).
        var intersectionWidth = OverlapLength(r1.Left, r1.Right, r2.Left, r2.Right);

        // Высота пересечения — длина перекрытия проекций прямоугольников на ось Y,
        // то есть длина общего участка отрезков [r1.Top, r1.Bottom] и [r2.Top, r2.Bottom].
        // Учтите: ось Y направлена вниз, поэтому «Top» — меньшая координата, «Bottom» — большая.
        // Равна 0, если по оси Y перекрытия нет или оно состоит из одной точки (касание).
        var intersectionHeight = OverlapLength(r1.Top, r1.Bottom, r2.Top, r2.Bottom);

        // Пересечение двух таких прямоугольников — прямоугольник (возможно, вырожденный)
        // со сторонами intersectionWidth и intersectionHeight, поэтому его площадь
        // равна произведению этих сторон.
        return intersectionWidth * intersectionHeight;
    }

    /// <summary>
    /// Определяет, целиком ли один из прямоугольников лежит внутри другого.
    /// </summary>
    /// <param name="r1">Первый прямоугольник.</param>
    /// <param name="r2">Второй прямоугольник.</param>
    /// <returns>
    /// Номер (с нуля) внутреннего прямоугольника:
    /// <list type="bullet">
    /// <item><description>0 — если r1 целиком находится внутри r2;</description></item>
    /// <item><description>1 — если r2 целиком находится внутри r1;</description></item>
    /// <item><description>-1 — если ни один прямоугольник не лежит целиком внутри другого.</description></item>
    /// </list>
    /// Если прямоугольники полностью совпадают, возвращается 0
    /// (по условию допустим номер любого из них).
    /// </returns>
    /// <remarks>
    /// Проверка «внутри» включает границы: прямоугольник считается лежащим
    /// внутри другого, если каждая его граница не выходит за соответствующую
    /// границу внешнего. Корректно работает с вырожденными прямоугольниками
    /// (отрезками и точками).
    /// </remarks>
    public static int IndexOfInnerRectangle(Rectangle r1, Rectangle r2)
    {
        // Результат проверки «r1 целиком лежит внутри r2»:
        // true — если все четыре границы r1 находятся в пределах соответствующих
        // границ r2 (совпадение границ допустимо); иначе false.
        var r1InsideR2 = IsInside(r1, r2);

        // Результат проверки «r2 целиком лежит внутри r1» — аналогично, но
        // направления проверки обратные.
        var r2InsideR1 = IsInside(r2, r1);

        if (r1InsideR2)
            return 0; // r1 внутри r2 (частный случай — прямоугольники совпадают:
                      // тогда оба флага true, и по условию допустим номер любого из них)
        if (r2InsideR1)
            return 1; // r2 внутри r1
        return -1;    // ни один прямоугольник не лежит целиком внутри другого
    }

    /// <summary>
    /// Проверяет, имеют ли два замкнутых отрезка [aStart, aEnd] и [bStart, bEnd]
    /// хотя бы одну общую точку.
    /// </summary>
    /// <param name="aStart">Начало первого отрезка (меньшая координата).</param>
    /// <param name="aEnd">Конец первого отрезка (большая координата).</param>
    /// <param name="bStart">Начало второго отрезка (меньшая координата).</param>
    /// <param name="bEnd">Конец второго отрезка (большая координата).</param>
    /// <returns>
    /// <see langword="true"/>, если отрезки перекрываются или касаются концом;
    /// иначе <see langword="false"/>.
    /// </returns>
    /// <remarks>
    /// Самое позднее начало отрезков (<c>Max(aStart, bStart)</c>) должно оказаться
    /// не правее самого раннего их конца (<c>Min(aEnd, bEnd)</c>).
    /// </remarks>
    private static bool HasCommonPoint(int aStart, int aEnd, int bStart, int bEnd)
    {
        // Позднее начало: максимальная из двух «левых» координат отрезков —
        // левая граница возможного общего участка.
        var latestStart = Math.Max(aStart, bStart);

        // Ранний конец: минимальная из двух «правых» координат отрезков —
        // правая граница возможного общего участка.
        var earliestEnd = Math.Min(aEnd, bEnd);

        // Отрезки имеют общую точку тогда и только тогда, когда позднее начало
        // не правее раннего конца (неравенство нестрогое — касание концами тоже
        // считается общей точкой).
        return latestStart <= earliestEnd;
    }

    /// <summary>
    /// Возвращает длину перекрытия двух замкнутых отрезков [aStart, aEnd]
    /// и [bStart, bEnd].
    /// </summary>
    /// <param name="aStart">Начало первого отрезка (меньшая координата).</param>
    /// <param name="aEnd">Конец первого отрезка (большая координата).</param>
    /// <param name="bStart">Начало второго отрезка (меньшая координата).</param>
    /// <param name="bEnd">Конец второго отрезка (большая координата).</param>
    /// <returns>
    /// Длина общего участка отрезков; 0, если отрезки не перекрываются
    /// или перекрываются только в одной точке (касание).
    /// </returns>
    /// <remarks>
    /// Перекрытие — это отрезок от <c>Max(aStart, bStart)</c> до <c>Min(aEnd, bEnd)</c>;
    /// если его «длина» отрицательна, значит общих точек нет, и результат округляется до 0.
    /// </remarks>
    private static int OverlapLength(int aStart, int aEnd, int bStart, int bEnd)
    {
        // Левая граница перекрытия — позднее из двух начал отрезков.
        var overlapStart = Math.Max(aStart, bStart);

        // Правая граница перекрытия — ранний из двух концов отрезков.
        var overlapEnd = Math.Min(aEnd, bEnd);

        // «Сырая» длина перекрытия. Если она отрицательна, значит общего участка нет;
        // Math.Max(0, ...) заменяет отрицательное значение нулём. При касании
        // (overlapEnd == overlapStart) длина равна 0 автоматически.
        var rawOverlap = overlapEnd - overlapStart;

        // Итоговая длина перекрытия: всегда неотрицательная.
        var overlap = Math.Max(0, rawOverlap);

        return overlap;
    }

    /// <summary>
    /// Проверяет, целиком ли прямоугольник <paramref name="inner"/> лежит
    /// внутри прямоугольника <paramref name="outer"/> (границы считаются частью
    /// прямоугольника, поэтому совпадение границ допустимо).
    /// </summary>
    /// <param name="inner">Проверяемый прямоугольник (потенциально внутренний).</param>
    /// <param name="outer">Прямоугольник, внутри которого проверяется <paramref name="inner"/>.</param>
    /// <returns>
    /// <see langword="true"/>, если все четыре границы <paramref name="inner"/>
    /// находятся в пределах соответствующих границ <paramref name="outer"/>;
    /// иначе <see langword="false"/>.
    /// </returns>
    /// <remarks>
    /// Достаточно проверить, что левая и верхняя границы внутреннего прямоугольника
    /// не левее/не выше внешних, а правая и нижняя — не правее/ниже.
    /// Так как Left &lt;= Right и Top &lt;= Bottom всегда, этого достаточно
    /// для полной вложенности, включая вырожденные прямоугольники.
    /// </remarks>
    private static bool IsInside(Rectangle inner, Rectangle outer)
    {
        // Левая граница inner не левее левой границы outer.
        var leftOk = outer.Left <= inner.Left;

        // Верхняя граница inner не выше верхней границы outer
        // (ось Y направлена вниз, поэтому «не выше» — это «меньшая или равная координата»).
        var topOk = outer.Top <= inner.Top;

        // Правая граница inner не правее правой границы outer.
        var rightOk = inner.Right <= outer.Right;

        // Нижняя граница inner не ниже нижней границы outer
        // («не ниже» — «меньшая или равная координата», так как ось Y направлена вниз).
        var bottomOk = inner.Bottom <= outer.Bottom;

        // Inner лежит внутри outer тогда и только тогда, когда все четыре
        // границы проходят проверку (совпадение границ допустимо).
        return leftOk && topOk && rightOk && bottomOk;
    }
}
