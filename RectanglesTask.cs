using System;

namespace Rectangles;

/// <summary>
/// Статический класс с тремя методами для работы с двумя прямоугольниками,
/// стороны которых параллельны осям координат.
/// </summary>
/// <remarks>
/// <para>
/// Координаты целочисленные. Используется «графическая» система координат:
/// верхний левый угол экрана — это (0, 0), а ось Y направлена вниз.
/// Поэтому у прямоугольника нижняя граница (<see cref="Rectangle.Bottom"/>)
/// имеет координату больше, чем верхняя (<see cref="Rectangle.Top"/>).
/// </para>
/// <para>
/// Граница и внутренность прямоугольника считаются частью прямоугольника,
/// то есть прямоугольник — это замкнутая область (включая вырожденные случаи:
/// отрезки при нулевой ширине или высоте и точки при обоих нулевых размерах).
/// </para>
/// <para>
/// Логика во всех методах основана на разложении двумерной задачи на две
/// одномерные: проекции прямоугольников на оси X и Y — это замкнутые отрезки
/// [Left, Right] и [Top, Bottom]. Два прямоугольника имеют общую точку тогда
/// и только тогда, когда их проекции имеют общую точку по обеим осям.
/// Вспомогательных методов нет — вся логика встроена в три основных метода.
/// </para>
/// </remarks>
public static class RectanglesTask
{
    /// <summary>
    /// Определяет, есть ли у двух прямоугольников хотя бы одна общая точка.
    /// Касание границами (по стороне или углу) также считается пересечением.
    /// </summary>
    /// <param name="r1">Первый прямоугольник.</param>
    /// <param name="r2">Второй прямоугольник.</param>
    /// <returns>
    /// <see langword="true"/>, если прямоугольники имеют хотя бы одну общую точку
    /// (пересекаются, касаются или один лежит внутри другого); иначе <see langword="false"/>.
    /// </returns>
    /// <remarks>
    /// Между замкнутыми отрезками [aStart, aEnd] и [bStart, bEnd] есть общая точка
    /// тогда и только тогда, когда <c>Max(aStart, bStart) &lt;= Min(aEnd, bEnd)</c>.
    /// Эта проверка применяется отдельно к проекциям на ось X и на ось Y;
    /// пересечение по обеим осям даёт общую точку прямоугольников.
    /// Условие корректно и для вырожденных прямоугольников (отрезков и точек).
    /// </remarks>
    public static bool AreIntersected(Rectangle r1, Rectangle r2)
    {
        // Позднее начало проекций на ось X: максимальная из «левых» координат —
        // левая граница возможного общего участка отрезков [r1.Left, r1.Right]
        // и [r2.Left, r2.Right].
        var latestStartX = Math.Max(r1.Left, r2.Left);

        // Ранний конец проекций на ось X: минимальная из «правых» координат —
        // правая граница возможного общего участка.
        var earliestEndX = Math.Min(r1.Right, r2.Right);

        // Пересечение по оси X: отрезки-проекции имеют общую точку, если позднее
        // начало не правее раннего конца (касание концами тоже считается).
        var intersectedByX = latestStartX <= earliestEndX;

        // Позднее начало проекций на ось Y: максимальная из «верхних» координат.
        // Учтите: ось Y направлена вниз, поэтому Top — меньшая координата,
        // а Bottom — большая.
        var latestStartY = Math.Max(r1.Top, r2.Top);

        // Ранний конец проекций на ось Y: минимальная из «нижних» координат.
        var earliestEndY = Math.Min(r1.Bottom, r2.Bottom);

        // Пересечение по оси Y: отрезки-проекции имеют общую точку, если позднее
        // начало не ниже раннего конца (касание краями тоже считается).
        var intersectedByY = latestStartY <= earliestEndY;

        // Прямоугольники имеют общую точку тогда и только тогда, когда
        // общие точки есть у проекций и на ось X, и на ось Y одновременно.
        return intersectedByX && intersectedByY;
    }

    /// <summary>
    /// Вычисляет площадь пересечения двух прямоугольников.
    /// </summary>
    /// <param name="r1">Первый прямоугольник.</param>
    /// <param name="r2">Второй прямоугольник.</param>
    /// <returns>
    /// Площадь общей части прямоугольников как целое число. Если прямоугольники
    /// не пересекаются, пересекаются только границами либо один из них вырожден
    /// (нулевая ширина или высота), результат равен 0.
    /// </returns>
    /// <remarks>
    /// Пересечение двух прямоугольников со сторонами, параллельными осям, —
    /// это прямоугольник (возможно, вырожденный), чьи стороны равны длинам
    /// перекрытия проекций исходных прямоугольников на соответствующие оси.
    /// Длина перекрытия отрезков [aStart, aEnd] и [bStart, bEnd] равна
    /// <c>Max(0, Min(aEnd, bEnd) - Max(aStart, bStart))</c>.
    /// </remarks>
    public static int IntersectionSquare(Rectangle r1, Rectangle r2)
    {
        // Левая граница перекрытия проекций на ось X — позднее из двух начал
        // отрезков [r1.Left, r1.Right] и [r2.Left, r2.Right].
        var overlapStartX = Math.Max(r1.Left, r2.Left);

        // Правая граница перекрытия проекций на ось X — ранний из двух концов.
        var overlapEndX = Math.Min(r1.Right, r2.Right);

        // Ширина пересечения — длина общего участка проекций на ось X.
        // Math.Max(0, ...) заменяет отрицательное значение (нет перекрытия) нулём;
        // при касании (overlapEndX == overlapStartX) ширина равна 0 автоматически.
        var intersectionWidth = Math.Max(0, overlapEndX - overlapStartX);

        // Верхняя граница перекрытия проекций на ось Y — позднее из двух начал
        // отрезков [r1.Top, r1.Bottom] и [r2.Top, r2.Bottom]
        // (ось Y направлена вниз, поэтому «Top» — меньшая координата).
        var overlapStartY = Math.Max(r1.Top, r2.Top);

        // Нижняя граница перекрытия проекций на ось Y — ранний из двух концов.
        var overlapEndY = Math.Min(r1.Bottom, r2.Bottom);

        // Высота пересечения — длина общего участка проекций на ось Y.
        // Равна 0, если по оси Y перекрытия нет или оно состоит из одной точки.
        var intersectionHeight = Math.Max(0, overlapEndY - overlapStartY);

        // Пересечение двух таких прямоугольников — прямоугольник (возможно,
        // вырожденный) со сторонами intersectionWidth и intersectionHeight,
        // поэтому его площадь равна произведению этих сторон.
        return intersectionWidth * intersectionHeight;
    }

    /// <summary>
    /// Определяет, целиком ли один из прямоугольников лежит внутри другого.
    /// </summary>
    /// <param name="r1">Первый прямоугольник.</param>
    /// <param name="r2">Второй прямоугольник.</param>
    /// <returns>
    /// Номер (с нуля) внутреннего прямоугольника:
    /// <list type="bullet">
    /// <item><description>0 — если r1 целиком находится внутри r2;</description></item>
    /// <item><description>1 — если r2 целиком находится внутри r1;</description></item>
    /// <item><description>-1 — если ни один прямоугольник не лежит целиком внутри другого.</description></item>
    /// </list>
    /// Если прямоугольники полностью совпадают, возвращается 0
    /// (по условию допустим номер любого из них).
    /// </returns>
    /// <remarks>
    /// Проверка «внутри» включает границы: прямоугольник считается лежащим
    /// внутри другого, если каждая его граница не выходит за соответствующую
    /// границу внешнего. Достаточно проверить четыре неравенства сразу:
    /// outer.Left &lt;= inner.Left, outer.Top &lt;= inner.Top,
    /// inner.Right &lt;= outer.Right, inner.Bottom &lt;= outer.Bottom.
    /// Корректно работает с вырожденными прямоугольниками (отрезками и точками).
    /// Если ни один прямоугольник не лежит внутри другого, возвращается -1 —
    /// в том числе когда они просто пересекаются или касаются границами.
    /// </remarks>
    public static int IndexOfInnerRectangle(Rectangle r1, Rectangle r2)
    {
        // r1 целиком лежит внутри r2, если все четыре его границы находятся
        // в пределах соответствующих границ r2 (совпадение границ допустимо):
        // левая и верхняя границы r1 не левее/не выше границ r2,
        // правая и нижняя — не правее/не ниже.
        var r1InsideR2 = r2.Left <= r1.Left && r2.Top <= r1.Top
                         && r1.Right <= r2.Right && r1.Bottom <= r2.Bottom;

        if (r1InsideR2)
            return 0; // r1 внутри r2 (частный случай — прямоугольники совпадают:
                      // тогда вторая проверка тоже истинна, и по условию
                      // допустим номер любого из них)

        // Аналогичная проверка в обратную сторону: r2 целиком лежит внутри r1,
        // если каждая граница r2 не выходит за соответствующую границу r1.
        var r2InsideR1 = r1.Left <= r2.Left && r1.Top <= r2.Top
                         && r2.Right <= r1.Right && r2.Bottom <= r1.Bottom;

        if (r2InsideR1)
            return 1; // r2 внутри r1

        return -1;    // ни один прямоугольник не лежит целиком внутри другого
    }
}
